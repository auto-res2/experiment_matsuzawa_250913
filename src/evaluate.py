"""Evaluation stub for ORCHID-D4 experiments.
This placeholder is required so that the Python package can be discovered
without syntax errors during smoke-tests.  Full evaluation logic will be
implemented in a later research iteration.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Any


def evaluate(run_file: Path) -> Dict[str, Any]:
    """Dummy evaluation that simply re-loads the metrics JSON created during a run.
    Parameters
    ----------
    run_file: Path
        Path to a JSON file generated by `main.py` in `.research/iteration2/`.
    Returns
    -------
    Dict[str, Any]
        The parsed JSON so that downstream smoke-tests have something concrete
        to inspect.
    """
    with run_file.open("r") as f:
        data = json.load(f)
    return data


if __name__ == "__main__":
    import argparse, pprint, sys

    parser = argparse.ArgumentParser(description="Evaluate an ORCHID-D4 run")
    parser.add_argument("run_json", type=str, help="Path to JSON produced by main.py")
    args = parser.parse_args()

    metrics = evaluate(Path(args.run_json))
    pprint.pp(metrics)